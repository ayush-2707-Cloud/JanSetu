/** Lookup helper — find a domain by its ID */
export function getDomainById(id: string): LegalDomain | undefined {
  return legalDomains.find((d) => d.id === id);
}

/** Lookup helper — find domain by a subcategory ID */
export function getDomainBySubcategoryId(subcatId: string): LegalDomain | undefined {
  return legalDomains.find((d) => d.subcategories.some((s) => s.id === subcatId));
}

/** Lookup helper — find subcategory by ID across all domains */
export function getSubcategoryById(subcatId: string): { domain: LegalDomain; subcategory: LegalDomainSubcategory } | undefined {
  for (const domain of legalDomains) {
    const sub = domain.subcategories.find((s) => s.id === subcatId);
    if (sub) return { domain, subcategory: sub };
  }
  return undefined;
}
